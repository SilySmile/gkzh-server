-- 职业飞行棋（zyfxq）基础结构、19 格棋盘、规则参数与 30 道题库；可重复执行。
-- 规范：所有业务表与字段必须提供中文 COMMENT；本脚本只创建 gkzh_zyfxq_* 表，
-- 不修改其他游戏数据。题目内容来自《飞行棋问答题(1).docx》，线上可在 Web 继续维护。
-- 适用 MySQL 5.7（不使用 CHECK 约束、窗口函数和 JSON 函数索引）。

CREATE TABLE IF NOT EXISTS gkzh_zyfxq_cell (
  cell_id BIGINT NOT NULL AUTO_INCREMENT COMMENT '格子编号（自增主键）',
  cell_no TINYINT NOT NULL COMMENT '棋盘格号，取值 1-19，按行进顺序编号',
  cell_type VARCHAR(16) NOT NULL DEFAULT 'normal' COMMENT '格子类型：normal普通格，question答题格，end终点',
  question_type VARCHAR(16) DEFAULT NULL COMMENT '答题格题目类型：career职业问答，scenario情景任务卡；普通格与终点为空',
  cell_color VARCHAR(16) NOT NULL DEFAULT '#FD9452' COMMENT '格子底色（十六进制），按设计稿采样，供小程序渲染',
  cell_label VARCHAR(50) DEFAULT NULL COMMENT '格子显示文案，例如职业问答、情景任务卡、终点；普通格为空',
  status CHAR(1) NOT NULL DEFAULT '0' COMMENT '状态：0启用，1停用；停用的答题格按普通格处理',
  create_time DATETIME DEFAULT NULL COMMENT '创建时间',
  update_time DATETIME DEFAULT NULL COMMENT '最后更新时间',
  PRIMARY KEY(cell_id),
  UNIQUE KEY uk_zyfxq_cell_no(cell_no)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='职业飞行棋棋盘格子配置';

CREATE TABLE IF NOT EXISTS gkzh_zyfxq_question (
  question_id BIGINT NOT NULL AUTO_INCREMENT COMMENT '题目编号',
  question_type VARCHAR(16) NOT NULL COMMENT '题目类型：career职业问答，scenario情景任务卡',
  title VARCHAR(500) NOT NULL COMMENT '题干',
  analysis VARCHAR(1000) DEFAULT NULL COMMENT '题目解析，用于答题反馈展示，可为空',
  sort_order INT NOT NULL DEFAULT 0 COMMENT '同类型内显示顺序，数值越小越靠前',
  status CHAR(1) NOT NULL DEFAULT '0' COMMENT '状态：0启用，1停用；停用题目不会被抽中',
  create_time DATETIME DEFAULT NULL COMMENT '创建时间',
  update_time DATETIME DEFAULT NULL COMMENT '最后更新时间',
  PRIMARY KEY(question_id),
  KEY idx_zyfxq_question_type(question_type,status)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='职业飞行棋题库';

CREATE TABLE IF NOT EXISTS gkzh_zyfxq_option (
  option_id BIGINT NOT NULL AUTO_INCREMENT COMMENT '选项编号',
  question_id BIGINT NOT NULL COMMENT '所属题目编号',
  option_label CHAR(1) NOT NULL COMMENT '选项字母：A、B、C、D',
  option_content VARCHAR(500) NOT NULL COMMENT '选项内容',
  is_correct CHAR(1) NOT NULL DEFAULT '0' COMMENT '是否正确答案：1是，0否；每题有且只有一个正确选项',
  sort_order INT NOT NULL DEFAULT 0 COMMENT '选项显示顺序，数值越小越靠前',
  create_time DATETIME DEFAULT NULL COMMENT '创建时间',
  PRIMARY KEY(option_id),
  UNIQUE KEY uk_zyfxq_option_label(question_id,option_label)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='职业飞行棋题目选项';

CREATE TABLE IF NOT EXISTS gkzh_zyfxq_setting (
  setting_id TINYINT NOT NULL COMMENT '配置编号，固定为1（单行配置）',
  total_seconds INT NOT NULL DEFAULT 180 COMMENT '单局总时长（秒），到点未抵达终点判定为未通关',
  question_seconds INT NOT NULL DEFAULT 20 COMMENT '单题限时（秒），超时按答错处理',
  back_steps TINYINT NOT NULL DEFAULT 2 COMMENT '答错或超时后退格数',
  dice_faces TINYINT NOT NULL DEFAULT 6 COMMENT '骰子面数，单骰取 1 到该值',
  enabled CHAR(1) NOT NULL DEFAULT '1' COMMENT '是否启用游戏：0停用，1启用；停用时学生端拒绝开局',
  create_time DATETIME DEFAULT NULL COMMENT '创建时间',
  update_time DATETIME DEFAULT NULL COMMENT '最后更新时间',
  PRIMARY KEY(setting_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='职业飞行棋规则参数（单行配置）';

CREATE TABLE IF NOT EXISTS gkzh_zyfxq_record (
  record_id BIGINT NOT NULL AUTO_INCREMENT COMMENT '参与记录编号',
  school_id BIGINT NOT NULL COMMENT '学校编号',
  instance_id BIGINT NOT NULL COMMENT '活动周实例编号',
  game_id BIGINT NOT NULL COMMENT '活动游戏编号',
  user_id BIGINT NOT NULL COMMENT '平台用户编号',
  student_id BIGINT DEFAULT NULL COMMENT '学生编号',
  student_no VARCHAR(50) DEFAULT NULL COMMENT '学号快照',
  student_name VARCHAR(100) DEFAULT NULL COMMENT '学生姓名快照',
  department_id BIGINT DEFAULT NULL COMMENT '专业（二级部门）编号，其父部门才是院系',
  major VARCHAR(100) DEFAULT NULL COMMENT '专业名称快照',
  gender VARCHAR(16) DEFAULT NULL COMMENT '性别快照：男、女，其他值表示未知',
  game_type VARCHAR(32) NOT NULL DEFAULT 'zyfxq' COMMENT '游戏类型，固定为zyfxq',
  status VARCHAR(16) NOT NULL DEFAULT 'ready' COMMENT '记录状态：ready已扫码未开始，playing对局中，finished本局已结束',
  result VARCHAR(8) DEFAULT NULL COMMENT '对局结果：win通关，lose未通关；对局中为空',
  attempt_no TINYINT NOT NULL DEFAULT 1 COMMENT '第几局，未通关重开后累加；参与记录仍只有一条',
  position TINYINT NOT NULL DEFAULT 0 COMMENT '当前所在格号，0表示仍在起点',
  roll_count INT NOT NULL DEFAULT 0 COMMENT '本局掷骰次数',
  step_total INT NOT NULL DEFAULT 0 COMMENT '本局累计前行总步数（骰子点数之和，不含后退）',
  dice_value TINYINT DEFAULT NULL COMMENT '最近一次掷出的点数',
  answer_count INT NOT NULL DEFAULT 0 COMMENT '本局已作答题数',
  correct_count INT NOT NULL DEFAULT 0 COMMENT '本局答对题数',
  timeout_count INT NOT NULL DEFAULT 0 COMMENT '本局超时题数',
  current_question_id BIGINT DEFAULT NULL COMMENT '当前待答题目编号；无待答题目为空',
  current_question_time DATETIME DEFAULT NULL COMMENT '当前题目下发时间，用于服务端计算作答耗时与超时',
  current_cell_no TINYINT DEFAULT NULL COMMENT '触发当前题目的格号',
  total_seconds INT NOT NULL DEFAULT 180 COMMENT '本局总时长（秒）快照，开局时固化',
  question_seconds INT NOT NULL DEFAULT 20 COMMENT '本局单题限时（秒）快照，开局时固化',
  back_steps TINYINT NOT NULL DEFAULT 2 COMMENT '本局答错后退格数快照，开局时固化',
  dice_faces TINYINT NOT NULL DEFAULT 6 COMMENT '本局骰子面数快照，开局时固化；单骰取 1 到该值',
  start_time DATETIME DEFAULT NULL COMMENT '本局开始时间；未点击开始游戏时为空',
  end_time DATETIME DEFAULT NULL COMMENT '本局结束时间：通关时间或超时截止时间',
  duration_ms INT DEFAULT NULL COMMENT '本局总耗时（毫秒），结束后写入，未结束为空',
  scan_time DATETIME NOT NULL COMMENT '首次扫码进入游戏时间',
  create_time DATETIME DEFAULT NULL COMMENT '创建时间',
  update_time DATETIME DEFAULT NULL COMMENT '最后更新时间',
  PRIMARY KEY(record_id),
  UNIQUE KEY uk_zyfxq_record_scope(school_id,instance_id,game_id,user_id),
  KEY idx_zyfxq_record_instance(instance_id,game_id),
  KEY idx_zyfxq_record_status(status,result),
  KEY idx_zyfxq_record_user(user_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='职业飞行棋学生参与记录';

CREATE TABLE IF NOT EXISTS gkzh_zyfxq_answer (
  answer_id BIGINT NOT NULL AUTO_INCREMENT COMMENT '答题明细编号',
  record_id BIGINT NOT NULL COMMENT '参与记录编号',
  attempt_no TINYINT NOT NULL COMMENT '第几局，与参与记录的 attempt_no 对应',
  cell_no TINYINT NOT NULL COMMENT '触发该题的格号',
  question_id BIGINT NOT NULL COMMENT '题目编号',
  question_type VARCHAR(16) NOT NULL COMMENT '题目类型快照：career职业问答，scenario情景任务卡',
  question_title VARCHAR(500) NOT NULL COMMENT '题干快照，题库后续修改不影响历史统计',
  option_label CHAR(1) DEFAULT NULL COMMENT '学生所选选项字母；超时未作答为空',
  option_content VARCHAR(500) DEFAULT NULL COMMENT '学生所选选项内容快照；超时未作答为空',
  correct_label CHAR(1) NOT NULL COMMENT '正确选项字母快照',
  correct_content VARCHAR(500) NOT NULL COMMENT '正确选项内容快照',
  is_correct CHAR(1) NOT NULL DEFAULT '0' COMMENT '是否答对：1答对，0答错或超时',
  is_timeout CHAR(1) NOT NULL DEFAULT '0' COMMENT '是否超时：1超时未作答，0已作答',
  limit_seconds INT NOT NULL COMMENT '题目限时（秒）快照',
  cost_ms INT NOT NULL DEFAULT 0 COMMENT '实际答题耗时（毫秒），由服务端下发与提交时间计算',
  position_before TINYINT NOT NULL COMMENT '答题前所处格号',
  position_after TINYINT NOT NULL COMMENT '答题后所处格号（答对不变，答错或超时后退）',
  create_time DATETIME DEFAULT NULL COMMENT '作答时间',
  PRIMARY KEY(answer_id),
  KEY idx_zyfxq_answer_record(record_id,attempt_no),
  KEY idx_zyfxq_answer_question(question_id),
  KEY idx_zyfxq_answer_timeout(is_timeout)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='职业飞行棋答题明细';


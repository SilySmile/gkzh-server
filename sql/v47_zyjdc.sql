CREATE TABLE IF NOT EXISTS gkzh_zyjdc_role (
  role_id BIGINT NOT NULL AUTO_INCREMENT COMMENT '角色编号',
  role_code VARCHAR(32) NOT NULL COMMENT '动物编码：elephant、lion、tiger、leopard、wolf、fox、cat、mouse',
  role_name VARCHAR(20) NOT NULL COMMENT '动物名称，例如大象、狮子',
  job_title VARCHAR(50) NOT NULL COMMENT '职场定位，例如首席执行官（CEO）',
  rank_level TINYINT NOT NULL COMMENT '对弈等级：大象8、狮子7、老虎6、豹子5、狼4、狐3、猫2、老鼠1',
  image_url VARCHAR(500) DEFAULT NULL COMMENT '角色头像地址，支持完整URL或相对路径',
  survival_rule TEXT COMMENT '该动物角色的生存法则',
  career_ability TEXT COMMENT '该动物角色对应的职场能力',
  role_interpretation TEXT COMMENT '学生选择该角色后的个人解读',
  positioning TEXT COMMENT '该角色对应的职场定位说明',
  advantage TEXT COMMENT '该角色对应的能力优势',
  sort_order INT NOT NULL DEFAULT 0 COMMENT '显示顺序，数值越小越靠前',
  status CHAR(1) NOT NULL DEFAULT '0' COMMENT '状态：0启用，1停用',
  create_time DATETIME DEFAULT NULL COMMENT '创建时间',
  update_time DATETIME DEFAULT NULL COMMENT '最后更新时间',
  PRIMARY KEY(role_id),
  UNIQUE KEY uk_zyjdc_role_code(role_code),
  UNIQUE KEY uk_zyjdc_role_rank(rank_level)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='职业角斗场动物角色配置';

CREATE TABLE IF NOT EXISTS gkzh_zyjdc_record (
  record_id BIGINT NOT NULL AUTO_INCREMENT COMMENT '参与记录编号',
  school_id BIGINT NOT NULL COMMENT '学校编号',
  instance_id BIGINT NOT NULL COMMENT '活动周实例编号',
  game_id BIGINT NOT NULL COMMENT '活动游戏编号',
  user_id BIGINT NOT NULL COMMENT '平台用户编号',
  student_id BIGINT DEFAULT NULL COMMENT '学生编号',
  student_no VARCHAR(50) DEFAULT NULL COMMENT '学号快照',
  student_name VARCHAR(100) DEFAULT NULL COMMENT '学生姓名快照',
  department_id BIGINT DEFAULT NULL COMMENT '专业（二级部门）编号，其上一级为院系',
  major VARCHAR(100) DEFAULT NULL COMMENT '专业名称快照',
  gender CHAR(1) DEFAULT NULL COMMENT '性别快照：0男，1女，其他值表示未知',
  game_type VARCHAR(32) NOT NULL DEFAULT 'zyjdc' COMMENT '游戏类型，固定为zyjdc',
  status VARCHAR(16) NOT NULL DEFAULT 'participating' COMMENT '参与状态：participating进行中，finished已完成（仅胜利）',
  stage VARCHAR(16) NOT NULL DEFAULT 'entered' COMMENT '业务阶段：entered已扫码，role_selected已选角色，playing对弈中，finished已结束',
  role_id BIGINT DEFAULT NULL COMMENT '所选角色编号',
  role_code VARCHAR(32) DEFAULT NULL COMMENT '所选动物编码快照',
  role_name VARCHAR(20) DEFAULT NULL COMMENT '所选动物名称快照',
  job_title VARCHAR(50) DEFAULT NULL COMMENT '所选角色职场定位快照',
  attempt_no INT NOT NULL DEFAULT 1 COMMENT '当前第几局，从1开始',
  board_json JSON DEFAULT NULL COMMENT '当前棋盘状态JSON：4×4棋子、回合、开始时间、落子记录',
  result VARCHAR(10) DEFAULT NULL COMMENT '对局结果：win胜利，lose失败，draw平局，未结束为空',
  result_reason VARCHAR(20) DEFAULT NULL COMMENT '结束原因：capture_all吃光对方，timeout时间到，no_move无子可动',
  remaining_seconds INT DEFAULT NULL COMMENT '结束结算时剩余秒数',
  move_count INT NOT NULL DEFAULT 0 COMMENT '本局双方累计落子步数',
  scan_time DATETIME NOT NULL COMMENT '扫码进入游戏时间',
  start_time DATETIME DEFAULT NULL COMMENT '本局开始时间，用于服务端3分钟计时',
  finish_time DATETIME DEFAULT NULL COMMENT '本局结束时间',
  create_time DATETIME DEFAULT NULL COMMENT '创建时间',
  update_time DATETIME DEFAULT NULL COMMENT '最后更新时间',
  PRIMARY KEY(record_id),
  UNIQUE KEY uk_zyjdc_record_scope(school_id,instance_id,game_id,user_id),
  KEY idx_zyjdc_record_instance(instance_id,game_id),
  KEY idx_zyjdc_record_result(result,status),
  KEY idx_zyjdc_record_user(user_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='职业角斗场学生参与记录';

